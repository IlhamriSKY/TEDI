/**
 * One-click registration of TEDI's own MCP server into whichever AI agents the
 * user has, so any of them can drive the editor they are running inside.
 *
 * The server itself is `scripts/mcp/server.mjs`, shipped as a bundle resource
 * (see `tauri.conf.json`). This module does the reading and writing through Tauri;
 * what goes in each file is `scripts/mcp/targets.mjs`, shared with `tedi mcp install`.
 * "Is it installed" is answered from the same files, not from a flag that can drift.
 *
 * NOTHING IS CREATED FOR A CLI THE USER DOES NOT HAVE. Every target names a path
 * that must already exist before it is even offered, so this never scatters
 * config files for tools nobody installed.
 */
import { invoke } from "@tauri-apps/api/core";
import { homeDir, resourceDir } from "@tauri-apps/api/path";
import { getIdentifier } from "@tauri-apps/api/app";
import {
  entryFor,
  readsAsInstalled,
  TARGETS,
  withEntry,
  withoutEntry,
  type Target,
} from "@mcp/targets.mjs";

export { TARGETS };
export type { Target };

/** Default port. Nothing else on the machine claims it, and it is what the
 *  driver's own docs have always used. */
export const DEFAULT_PORT = 9222;

/**
 * Where an entry is written.
 *
 * `global` is the user-wide config in the home directory - the CLI loads it in
 * every session. `project` is the CLI's OWN project-scoped file inside the open
 * folder, which the CLI reads only while its working directory is that folder,
 * and which can be committed so a repo carries its own MCP wiring. Each is at a
 * documented standard path, and an agent with none is simply not offered there; see `TARGETS`.
 */
export type Scope = "global" | "project";

const slash = (p: string): string => p.replace(/\\/g, "/").replace(/\/+$/, "");

let cachedHome: string | null = null;
async function home(): Promise<string> {
  cachedHome ??= slash(await homeDir());
  return cachedHome;
}

/**
 * Absolute path of the bundled MCP server.
 *
 * A resource, not a repo path: an installed TEDI has no `scripts/` directory,
 * and a config entry pointing into one would work on the machine that wrote it
 * and nowhere else.
 */
let cachedServer: string | null = null;
/**
 * The bundle id of the TEDI doing the install, e.g. `id.ilhamrisky.tedi` (or
 * `.dev`). The one thing stamped into the generated config.
 *
 * WHY IT HAS TO BE WRITTEN DOWN. It names the app: the bridge's handshake file and
 * the pack switches both live in a directory named by this id. Without it a config
 * generated by a dev build read the RELEASE app's switches, and toggling a pack
 * changed nothing the CLI could see.
 *
 * No port beside it any more. No tool needs one, and a port written here is an
 * override the server obeys whenever the bridge is down: it then drives whichever
 * TEDI holds that port.
 */
async function bundleId(): Promise<string> {
  cachedBundle ??= await getIdentifier();
  return cachedBundle;
}
let cachedBundle: string | null = null;

export async function serverPath(): Promise<string> {
  cachedServer ??= `${slash(await resourceDir())}/mcp/server.mjs`;
  return cachedServer;
}

async function exists(path: string): Promise<boolean> {
  try {
    await invoke("fs_canonicalize", { path });
    return true;
  } catch {
    return false;
  }
}

/**
 * File contents, or "" ONLY when the file genuinely does not exist yet.
 *
 * Everything else throws, and that matters more than it looks: "" is what tells
 * the writer to start a fresh config. A permission error, a file too large, a
 * binary sniff - anything that quietly returned "" here would take the user's
 * existing `.claude.json`, with every project and MCP server in it, and replace
 * it with a file containing one entry.
 */
async function readOrEmpty(path: string): Promise<string> {
  if (!(await exists(path))) return "";
  const res = (await invoke("fs_read_file", { path })) as { kind?: string; content?: string };
  if (res.kind !== "text" || typeof res.content !== "string") {
    throw new Error(
      `${path} is not a readable text file (${res.kind ?? "unknown"}); leaving it alone.`,
    );
  }
  return res.content;
}

async function writeFile(path: string, content: string): Promise<void> {
  const dir = path.slice(0, path.lastIndexOf("/"));
  if (dir && !(await exists(dir))) await invoke("fs_create_dir", { path: dir });
  await invoke("fs_write_file", { path, content });
}

// --- public API ------------------------------------------------------------

export type TargetStatus = Target & {
  /** Which scope this row was resolved for. */
  scope: Scope;
  /** The CLI is installed on this machine (and, for `project`, a folder is open). */
  present: boolean;
  /** Our entry is in its config and points at this TEDI. */
  installed: boolean;
  /** Absolute config path, for the dialog. Empty only for `project` with no open
   *  folder, which `present:false` already flags. */
  path: string;
};

/**
 * The config file for one target in one scope, and whether it can be written.
 *
 * `project` needs an open FOLDER: without one there is nowhere to put a
 * project-scoped file, so `present` is false and `path` is empty. Both scopes
 * still gate on the CLI being installed here - a project `.mcp.json` for a CLI
 * the user does not have is a file nothing reads.
 */
async function resolve(
  target: Target,
  scope: Scope,
  root: string | null,
): Promise<{ path: string; present: boolean }> {
  const h = await home();
  const cliPresent = (await Promise.all(target.probes.map((p) => exists(`${h}/${p}`)))).some(
    Boolean,
  );
  if (scope === "project") {
    // Not every agent has one: Hermes reads a single global file.
    if (!root || !target.projectFile) return { path: "", present: false };
    return { path: `${slash(root)}/${target.projectFile}`, present: cliPresent };
  }
  return { path: `${h}/${target.file}`, present: cliPresent };
}

/**
 * Every target in one scope: where its config is, whether the CLI is here, and
 * whether we are wired into it. `root` is the OPEN FOLDER (the focused terminal's
 * cwd), used only for `project`.
 */
export async function detect(scope: Scope, root: string | null): Promise<TargetStatus[]> {
  const [server, bundle] = await Promise.all([serverPath(), bundleId()]);
  return await Promise.all(
    TARGETS.map(async (t) => {
      const { path, present } = await resolve(t, scope, root);
      // Per target, not per run. `readOrEmpty` throws on anything it cannot read
      // as text - and `~/.claude.json` is the one file here that realistically
      // trips the 10 MB read cap, because it carries Claude Code's whole project
      // history. One unreadable config must degrade to "not installed" for that
      // row, not take the other four rows and the indicator down with it.
      //
      // Only the READ is forgiving. `install` deliberately still throws on the
      // same file, because there the alternative is treating an unreadable
      // config as empty and replacing it.
      let installed = false;
      try {
        installed = present && readsAsInstalled(t, await readOrEmpty(path), server, bundle);
      } catch {
        installed = false;
      }
      return { ...t, scope, path, present, installed };
    }),
  );
}

/** Add (or repair) our entry in one target's config for `scope`. */
export async function install(target: Target, scope: Scope, root: string | null): Promise<void> {
  const { path, present } = await resolve(target, scope, root);
  if (!path) throw new Error(`No project-scoped config here for ${target.name}.`);
  if (!present) throw new Error(`${target.name} is not installed on this machine.`);
  const server = await serverPath();
  await writeFile(path, withEntry(target, await readOrEmpty(path), server, await bundleId()));
}

/** Remove our entry, leaving the rest of the file untouched. */
export async function uninstall(target: Target, scope: Scope, root: string | null): Promise<void> {
  const { path } = await resolve(target, scope, root);
  if (!path) return;
  const text = await readOrEmpty(path);
  if (!text.trim()) return;
  await writeFile(path, withoutEntry(target, text));
}

/** Exported for `scripts/mcp/install-verify.ts`, which drives the file edits
 *  against real config text without touching anyone's home directory. */
export const _internals = { withEntry, withoutEntry, readsAsInstalled, entryFor };
